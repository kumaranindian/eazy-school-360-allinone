#!/usr/bin/env python3
"""Generates docs/security/firestore-collection-inventory.md from firestore.rules:
every match block with, per operation, the authorization helpers it relies on.
Run: python3 tool/gen_rules_inventory.py > docs/security/firestore-collection-inventory.md"""
import re

src = open('firestore.rules').read()
# strip comments
src = re.sub(r'//[^\n]*', '', src)
skip = {'if', 'let', 'return', 'true', 'false', 'null', 'get', 'exists', 'existsAfter', 'getAfter', 'string',
        'int', 'size', 'matches', 'lower', 'hasOnly', 'hasAny', 'keys', 'diff', 'affectedKeys', 'is', 'in'}


def blocks(text, pos=0, prefix=''):
    out = []
    for m in re.finditer(r'match\s+(/[^\s{]*(?:\{[^}]*\}[^\s{]*)*)\s*\{', text):
        pass
    return out


# Walk braces manually.
i = 0
stack = []  # (kind, name, start)
out = []
tokens = re.finditer(r'match\s+(/[^\s{]*(?:\{[^}]*\}[^\s{]*)*)\s*\{|\{|\}', src)
paths = []
open_stack = []
for t in tokens:
    s = t.group(0)
    if s.startswith('match'):
        open_stack.append(('match', t.group(1), t.end()))
    elif s == '{':
        open_stack.append(('brace', None, t.end()))
    else:
        kind, name, start = open_stack.pop()
        if kind == 'match':
            body = src[start:t.start()]
            full = ''.join(n for k, n, _ in open_stack if k == 'match') + name
            out.append((full, body))


def own_body(body):
    # remove nested match blocks
    res = []
    depth = 0
    i = 0
    while i < len(body):
        m = re.match(r'match\s+/[^\s{]*(?:\{[^}]*\}[^\s{]*)*\s*\{', body[i:])
        if m and depth == 0:
            d = 1
            j = i + m.end()
            while j < len(body) and d:
                if body[j] == '{': d += 1
                elif body[j] == '}': d -= 1
                j += 1
            i = j
            continue
        res.append(body[i])
        i += 1
    return ''.join(res)


rows = []
for full, body in out:
    b = own_body(body)
    allows = re.findall(r'allow\s+([\w,\s]+?)\s*:\s*if\s+(.*?);', b, re.S)
    if not allows:
        continue
    ops = {}
    for names, cond in allows:
        helpers = sorted({h for h in re.findall(r'\b([A-Za-z_]\w+)\(', cond) if h not in skip})
        roles = sorted({r for r in re.findall(r"'(PLATFORM_ADMIN|SCHOOL_ADMIN|BRANCH_ADMIN|TEACHER|FINANCE|PARENT)'", cond)})
        for op in [n.strip() for n in names.split(',')]:
            ops.setdefault(op, []).append((helpers, roles, cond.strip() == 'false'))
    rows.append((full, ops))

print('# Firestore collection inventory (generated)\n')
print('Generated by `tool/gen_rules_inventory.py` from `firestore.rules`. For each match block and operation: the authorization helpers the rule calls (see the helper reference in `docs/security/role-permission-matrix.md`), explicit role literals, or **denied** when the rule is `false`. Operations: `read` = get+list, `create`, `update`, `delete`.\n')
print('Paths are relative to `/databases/{database}/documents`; `…` = `/schools/{s}/branches/{b}`.\n')
print('| Path | read | create | update | delete |')
print('|---|---|---|---|---|')
for full, ops in rows:
    p = full.replace('/databases/{database}/documents', '').replace('/schools/{schoolId}/branches/{branchId}', '…').replace('{schoolId}', '{s}').replace('{branchId}', '{b}')
    def cell(*keys):
        parts = []
        for k in keys:
            for helpers, roles, deny in ops.get(k, []):
                if deny:
                    parts.append('**denied**')
                else:
                    x = ', '.join(f'`{h}`' for h in helpers[:6])
                    if roles: x += (' · ' if x else '') + '/'.join(r.lower() for r in roles)
                    parts.append(x or '(own/field checks)')
        return '<br>'.join(dict.fromkeys(parts)) or '—'
    print(f'| `{p}` | {cell("read", "get", "list")} | {cell("create")} | {cell("update")} | {cell("delete")} |')
